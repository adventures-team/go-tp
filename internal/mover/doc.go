/*
Package mover - логика утилиты queued-mover: перенос событий очередей из одного кластера
queued (источник, A) в другой (приёмник, B) поверх [queuedclient].

Воркер каждой очереди в цикле получает активные события из A (Client.GetActive), публикует
их в B как есть (Client.Publish, тело события не декодируется) и удаляет из A
(Client.Delete); события, которые опубликовать не удалось, откладываются в A
(Client.Defer) и переносятся позже. Супервизор ([Mover.Run]) запускает воркеры по списку
очередей из onlineconf, перечитывает настройки на лету, пишет прогресс в лог и в режиме
one-shot завершает работу, когда во всех очередях A не осталось событий.

Запуск, конфигурация и гарантии описаны в godoc cmd/queued-mover и в docs/README.md.
*/
